  /**
   * Obtém a tradução para uma chave dada
   */
  function t(key, fallback = "") {
    // 1. Tenta no idioma selecionado
    const langDict = translations[currentLang];
    if (langDict && langDict[key] !== undefined && langDict[key] !== "") {
      return langDict[key];
    }
    // 2. Fallback prioritário para en-GB
    const enDict = translations["en-GB"];
    if (enDict && enDict[key] !== undefined && enDict[key] !== "") {
      return enDict[key];
    }
    // 3. Fallback secundário para pt-PT
    const ptDict = translations["pt-PT"];
    if (ptDict && ptDict[key] !== undefined && ptDict[key] !== "") {
      return ptDict[key];
    }
    return fallback || key;
  }

  /**
   * Inicializa o gestor de idioma
   */
  function init() {
    loadSavedLanguage();
    setupDropdown();
    applyTranslations();
  }

  /**
   * Determina o idioma inicial (URL param > localStorage > Default pt-PT)
   */
  function loadSavedLanguage() {
    const urlParams = new URLSearchParams(window.location.search);
    const langParam = urlParams.get("lang") || urlParams.get("locale");

    if (langParam) {
      const normalized = normalizeLang(langParam);
      if (normalized) {
        currentLang = normalized;
        saveLanguage(currentLang);
        return;
      }
    }

    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved && SUPPORTED_LANGS.includes(saved)) {
        currentLang = saved;
      } else {
        currentLang = DEFAULT_LANG;
      }
    } catch (e) {
      currentLang = DEFAULT_LANG;
    }
  }

  function normalizeLang(langStr) {
    const lower = (langStr || "").toLowerCase().trim();
    if (lower.startsWith("en") || lower.includes("english")) return "en-GB";
    if (lower.startsWith("it") || lower.includes("italian")) return "it-IT";
    if (lower.startsWith("fr") || lower.includes("french") || lower.includes("francais")) return "fr-FR";
    if (lower.startsWith("es") || lower.includes("spanish") || lower.includes("espanol")) return "es-ES";
    if (lower.startsWith("pl") || lower.includes("polish") || lower.includes("polski")) return "pl-PL";
    if (lower.startsWith("nl") || lower.includes("vlaams") || lower.includes("dutch") || lower.startsWith("bl") || lower.includes("be")) return "nl-BE";
    if (lower.startsWith("pt") || lower.includes("portuguese") || lower.includes("portugues")) return "pt-PT";
    return null;
  }

  function saveLanguage(lang) {
    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch (e) {}
  }

  /**
   * Configura os elementos de seleção de idioma (<select id="lang-select"> e <select id="auth-lang-select">)
   */
  function setupDropdown() {
    const headerSelect = document.getElementById("lang-select");
    if (headerSelect) {
      headerSelect.value = currentLang;
      headerSelect.addEventListener("change", (e) => {
        setLanguage(e.target.value);
      });
    }

    const authSelect = document.getElementById("auth-lang-select");
    if (authSelect) {
      authSelect.value = currentLang;
      authSelect.addEventListener("change", (e) => {
        setLanguage(e.target.value);
      });
    }
  }

  /**
   * Muda o idioma ativo e atualiza toda a aplicação
   */
  function setLanguage(newLang) {
    if (!SUPPORTED_LANGS.includes(newLang)) return;
    currentLang = newLang;
    saveLanguage(newLang);

    const headerSelect = document.getElementById("lang-select");
    if (headerSelect && headerSelect.value !== newLang) {
      headerSelect.value = newLang;
    }

    const authSelect = document.getElementById("auth-lang-select");
    if (authSelect && authSelect.value !== newLang) {
      authSelect.value = newLang;
    }

    // Atualizar atributo html lang
    document.documentElement.lang = newLang.split("-")[0];

    // Atualizar título do documento
    document.title = t("meta.title");

    // Aplicar textos estáticos
    applyTranslations();

    // Atualizar dinamicamente o select de países
    const cSelect = document.getElementById("results-country-select");
    if (cSelect) {
      const optAll = cSelect.querySelector('option[value="all"]');
      const optPt = cSelect.querySelector('option[value="pt"]');
      const optEs = cSelect.querySelector('option[value="es"]');
      const optIt = cSelect.querySelector('option[value="it"]');
      const optFr = cSelect.querySelector('option[value="fr"]');
      const optBl = cSelect.querySelector('option[value="bl"]');
      const optPl = cSelect.querySelector('option[value="pl"]');
      
      if (optAll) optAll.textContent = "🇪🇺 " + t("results.euConsolidated");
      if (optPt) optPt.textContent = "🇵🇹 " + t("country.pt");
      if (optEs) optEs.textContent = "🇪🇸 " + t("country.es");
      if (optIt) optIt.textContent = "🇮🇹 " + t("country.it");
      if (optFr) optFr.textContent = "🇫🇷 " + t("country.fr");
      if (optBl) optBl.textContent = "🇧🇪 " + t("country.bl");
      if (optPl) optPl.textContent = "🇵🇱 " + t("country.pl");
    }

    // Disparar um evento global para re-renderizar todos os gráficos do dashboard
    if (typeof window.dispatchEvent === "function" && typeof CustomEvent !== "undefined") {
      window.dispatchEvent(new CustomEvent("languageChanged", { detail: { lang: currentLang } }));
    }
    if (window.resultsDashboard && typeof window.resultsDashboard.renderAllDashboardMetrics === "function") {
      window.resultsDashboard.renderAllDashboardMetrics();
    } else if (window.ResultsDashboard && typeof window.ResultsDashboard.renderAllDashboardMetrics === "function") {
      window.ResultsDashboard.renderAllDashboardMetrics();
    }

    // Notificar os restantes módulos dinâmicos
    if (window.renderSchedule) window.renderSchedule();
    if (window.renderGF1) window.renderGF1();
    if (typeof window.renderSessionGallery === "function") {
      window.renderSessionGallery();
    }
    if (window.renderResultsAndMedia) window.renderResultsAndMedia();
    if (window.renderPartners) window.renderPartners();
    if (window.renderQuestionnaireGuide) window.renderQuestionnaireGuide();
    if (window.LiveSession && typeof window.LiveSession.render === "function") {
      window.LiveSession.render();
    }
    if (window.ResultsDashboard && typeof window.ResultsDashboard.renderKpiCards === "function") {
      window.ResultsDashboard.renderKpiCards();
    }
    if (window.ResultsDashboard && typeof window.ResultsDashboard.fetchData === "function") {
      window.ResultsDashboard.fetchData(false);
    }
    if (window.AuthModule) {
      if (typeof window.AuthModule.renderCodesDropdown === "function") window.AuthModule.renderCodesDropdown();
      if (typeof window.AuthModule.syncUIWithPhase === "function") window.AuthModule.syncUIWithPhase();
      if (typeof window.AuthModule.syncUIWithStatus === "function") window.AuthModule.syncUIWithStatus();
      if (typeof window.AuthModule.renderHeaderUserBadge === "function") window.AuthModule.renderHeaderUserBadge();
    }
    if (window.ModeratorPanel && typeof window.ModeratorPanel.updateSubmissionsGrid === "function") {
      window.ModeratorPanel.updateSubmissionsGrid();
    }
    if (typeof window.initVideoSlider === "function") {
      window.initVideoSlider();
    }

    if (window.lucide) {
      window.lucide.createIcons();
    }

    console.info(`🌐 Idioma alterado para: ${newLang}`);
  }

  /**
   * Itera pelos elementos com data-i18n e substitui os textos
   */
  function applyTranslations() {
    // 1. Textos e HTML
    document.querySelectorAll("[data-i18n]").forEach(el => {
      const key = el.getAttribute("data-i18n");
      const translation = t(key);
      if (translation && translation !== key) {
        const textSpan = el.querySelector("span:not([data-lucide])");
        if (textSpan && el.querySelector("[data-lucide], svg, i")) {
          textSpan.innerHTML = translation;
        } else {
          el.innerHTML = translation;
        }
      }
    });

    // 2. Placeholders
    document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
      const key = el.getAttribute("data-i18n-placeholder");
      const translation = t(key);
      if (translation && translation !== key) {
        el.placeholder = translation;
      }
    });

    // 3. Titles e Tooltips
    document.querySelectorAll("[data-i18n-title]").forEach(el => {
      const key = el.getAttribute("data-i18n-title");
      const translation = t(key);
      if (translation && translation !== key) {
        el.title = translation;
      }
    });

    // 4. Select de Países (Results & Media)
    const cSelect = document.getElementById("results-country-select");
    if (cSelect) {
      const optAll = cSelect.querySelector('option[value="all"]');
      const optPt = cSelect.querySelector('option[value="pt"]');
      const optEs = cSelect.querySelector('option[value="es"]');
      const optIt = cSelect.querySelector('option[value="it"]');
      const optFr = cSelect.querySelector('option[value="fr"]');
      const optBl = cSelect.querySelector('option[value="bl"]');
      const optPl = cSelect.querySelector('option[value="pl"]');
      
      if (optAll) optAll.textContent = "🇪🇺 " + t("results.euConsolidated");
      if (optPt) optPt.textContent = "🇵🇹 " + t("country.pt");
      if (optEs) optEs.textContent = "🇪🇸 " + t("country.es");
      if (optIt) optIt.textContent = "🇮🇹 " + t("country.it");
      if (optFr) optFr.textContent = "🇫🇷 " + t("country.fr");
      if (optBl) optBl.textContent = "🇧🇪 " + t("country.bl");
      if (optPl) optPl.textContent = "🇵🇱 " + t("country.pl");
    }
  }

  return {
    init,
    t,
    getLanguage: () => currentLang,
    getCurrentLanguage: () => currentLang,
    isEnglish: () => currentLang === "en-GB",
    setLanguage
  };
